//! The generator core: determinism, order, paths, head lines, classes, slots (S2 of the plan).
mod support;
use fs_blueprint::emit::header::{blueprint_hash, class_of, form_of, stamp, Form};
use fs_blueprint::emit::{generate, generate_with, join, Artifact, Class, Emitter};
use fs_blueprint::{Blueprint, Coded, KitCatalog};
use support::synth::{blueprint, COUNT};
use support::{edit, FakeCatalog, TASKS};

fn all() -> Vec<Blueprint> {
    let mut v: Vec<Blueprint> = (0..COUNT).map(blueprint).collect();
    v.push(Blueprint::from_toml(TASKS).unwrap());
    v
}

fn gen(bp: &Blueprint) -> Vec<Artifact> {
    generate(bp, &FakeCatalog).expect("generates")
}

#[test]
fn generating_twice_gives_byte_identical_output() {
    for bp in all() {
        let first = gen(&bp);
        for _ in 0..20 {
            assert_eq!(first, gen(&bp), "{}", bp.program.name);
        }
    }
}

#[test]
fn generating_a_second_later_gives_the_same_bytes_no_time_stamp() {
    let bp = blueprint(0);
    let first = gen(&bp);
    std::thread::sleep(std::time::Duration::from_millis(1100));
    let second = gen(&bp);
    assert_eq!(first, second);
    for a in &first {
        assert!(!a.content.contains("20"), "a year or time in {}", a.path);
    }
}

#[test]
fn the_output_is_sorted_by_path_and_without_duplicates() {
    for bp in all() {
        let paths: Vec<String> = gen(&bp).into_iter().map(|a| a.path).collect();
        assert!(paths.len() >= 3);
        let mut sorted = paths.clone();
        sorted.sort();
        sorted.dedup();
        assert_eq!(paths, sorted);
    }
}

#[test]
fn every_path_is_relative_with_slashes_on_every_platform() {
    for a in gen(&blueprint(1)) {
        assert!(!a.path.contains('\\'), "{}", a.path);
        assert!(
            !a.path.starts_with('/') && !a.path.contains(':'),
            "{}",
            a.path
        );
    }
    assert_eq!(join(&["a", "b", "c.rs"]), "a/b/c.rs");
}

#[test]
fn every_generated_file_has_its_head_line_with_version_and_blueprint_hash() {
    for bp in all() {
        let hash = blueprint_hash(&bp).unwrap();
        assert_eq!(hash.len(), 64);
        assert!(hash.chars().all(|c| c.is_ascii_hexdigit()));
        for a in gen(&bp) {
            let first = a.content.lines().next().unwrap();
            assert_eq!(class_of(&a.content), Some(a.class), "{}", a.path);
            assert!(first.contains(env!("CARGO_PKG_VERSION")), "{first}");
            match a.class {
                Class::Generated => {
                    assert!(first.contains("generated by fs-blueprint"), "{first}");
                    assert!(first.contains(&format!("sha256 {hash}")), "{first}");
                }
                Class::Seed => {
                    assert!(first.contains("created by fs-blueprint"), "{first}");
                    assert!(!first.contains("sha256"), "{first}");
                }
                Class::Exception => panic!("no exception here: {}", a.path),
            }
        }
    }
}

#[test]
fn the_head_line_has_the_comment_form_of_the_file_kind() {
    let h = "0".repeat(64);
    let line = |p: &str| {
        stamp(p, Class::Generated, &h, "x\n")
            .unwrap()
            .lines()
            .next()
            .unwrap()
            .to_string()
    };
    assert!(line("a/b.rs").starts_with("// generated by fs-blueprint"));
    assert!(line("a/b.toml").starts_with("# generated by fs-blueprint"));
    assert!(line(".gitattributes").starts_with("# generated by"));
    assert!(
        line("a/README.md").starts_with("<!-- generated by")
            && line("a/README.md").ends_with(" -->")
    );
    assert_eq!(form_of("x/y.yml"), Some(Form::Hash));
    assert_eq!(form_of("x/y.png"), None);
    assert_eq!(
        stamp("x/y.png", Class::Generated, &h, "")
            .unwrap_err()
            .to_string(),
        "header-unsupported{path=x/y.png}"
    );
    assert_eq!(stamp("a.rs", Class::Exception, &h, "body").unwrap(), "body");
}

#[test]
fn the_hash_follows_the_content_of_the_blueprint_not_its_spelling() {
    let base = blueprint_hash(&Blueprint::from_toml(TASKS).unwrap()).unwrap();
    let spaced = format!(
        "# a comment\n{}",
        TASKS.replace("name = \"tasks\"", "name   =   \"tasks\"")
    );
    assert_eq!(
        base,
        blueprint_hash(&Blueprint::from_toml(&spaced).unwrap()).unwrap()
    );
    let changed = edit(TASKS, "Tasks, dependencies and boards", "Tasks and boards");
    assert_ne!(
        base,
        blueprint_hash(&Blueprint::from_toml(&changed).unwrap()).unwrap()
    );
    let other = edit(
        TASKS,
        "version = \"0.0.29\"\n\n[[module]]\nname = \"task-card\"",
        "version = \"0.0.30\"\n\n[[module]]\nname = \"task-card\"",
    );
    assert_ne!(
        base,
        blueprint_hash(&Blueprint::from_toml(&other).unwrap()).unwrap()
    );
}

struct Own;
impl Emitter for Own {
    fn emit(&self, _: &Blueprint, _: &dyn KitCatalog) -> Result<Vec<Artifact>, Coded> {
        Ok(vec![Artifact::new(
            "crates/fs-beta-shelf-planner-core/src/own1.rs",
            Class::Generated,
            "x\n",
        )])
    }
}

#[test]
fn a_file_covered_by_an_exception_of_the_blueprint_is_class_exception_without_head() {
    let bp = blueprint(1);
    assert_eq!(
        bp.exception[0].paths[0],
        "crates/fs-beta-shelf-planner-core/src/own1.rs"
    );
    let out = generate_with(&bp, &FakeCatalog, &[&Own]).unwrap();
    assert_eq!(
        out,
        [Artifact::new(
            "crates/fs-beta-shelf-planner-core/src/own1.rs",
            Class::Exception,
            "x\n"
        )]
    );
}

struct Fixed(Vec<Artifact>);
impl Emitter for Fixed {
    fn emit(&self, _: &Blueprint, _: &dyn KitCatalog) -> Result<Vec<Artifact>, Coded> {
        Ok(self.0.clone())
    }
}

fn refused(list: Vec<Artifact>) -> String {
    generate_with(&blueprint(0), &FakeCatalog, &[&Fixed(list)])
        .unwrap_err()
        .to_string()
}

#[test]
fn an_emitter_cannot_make_a_file_an_exception_the_blueprint_does_not_name() {
    assert_eq!(
        refused(vec![Artifact::new("a.rs", Class::Exception, "x")]),
        "exception-undeclared{path=a.rs}"
    );
}

#[test]
fn two_emitters_on_one_path_and_invalid_paths_and_unknown_file_kinds_are_refused() {
    let a = Artifact::new("a.rs", Class::Generated, "x");
    assert_eq!(refused(vec![a.clone(), a]), "artifact-duplicate{path=a.rs}");
    for bad in ["a\\b.rs", "/a.rs", "../a.rs", "a/*.rs", ""] {
        assert!(
            refused(vec![Artifact::new(bad, Class::Generated, "x")]).starts_with("path-invalid"),
            "{bad}"
        );
    }
    assert_eq!(
        refused(vec![Artifact::new("a.bin", Class::Generated, "x")]),
        "header-unsupported{path=a.bin}"
    );
}

#[test]
fn every_finding_of_the_generator_conforms_to_the_code_list() {
    let errs = [
        "slot-unknown{name=x}",
        "slot-open{path=p}",
        "header-unsupported{path=p}",
        "artifact-duplicate{path=p}",
        "exception-undeclared{path=p}",
        "generated-changed{path=p}",
        "generated-missing{path=p}",
        "seed-missing{path=p}",
        "write-failed{path=p}",
    ];
    for e in errs {
        let code = e.split('{').next().unwrap();
        assert!(
            fs_blueprint::CODES.iter().any(|(c, _)| *c == code),
            "{code}"
        );
        for lang in ["en", "de"] {
            let m = fs_blueprint::messages::message(code, lang).unwrap();
            assert!(m.contains("{$"), "{code} {lang}");
        }
    }
}
