//! Pattern: Golden master (the files `new` writes for a package of kind data are compared byte for byte with `tests/data/gold/data/`; after a change on purpose the gold
//! files are written again from the new output and read by a person) + Single source (the `.desktop` of the RPM is the file of `packaging/` without its head line).
use fs_blueprint::cli::run;
use fs_blueprint::package_rpm::program_spec;
use fs_blueprint::Blueprint;
use std::path::{Path, PathBuf};

const DATA: &[&str] = &[
    ".gitattributes",
    ".github/workflows/check.yml",
    ".github/workflows/windows.yml",
    "packaging/net.freesynergy.Demo.desktop",
];

fn example() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/data/repos/ok")
}

fn cli(words: &[&str]) -> (i32, String) {
    let words: Vec<String> = words.iter().map(|w| (*w).to_string()).collect();
    let (mut out, mut err) = (Vec::new(), Vec::new());
    let code = run(&words, &mut out, &mut err);
    (
        code,
        String::from_utf8(out).unwrap() + &String::from_utf8(err).unwrap(),
    )
}

/// `new` on a copy of the example folder whose `scaffold.toml` has the given text.
fn made(name: &str, scaffold: &str) -> PathBuf {
    let base =
        Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("data-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&base);
    let (src, dir) = (base.join("src"), base.join("out"));
    std::fs::create_dir_all(src.join("forms")).unwrap();
    std::fs::write(src.join("scaffold.toml"), scaffold).unwrap();
    std::fs::copy(
        example().join("forms/demo.toml"),
        src.join("forms/demo.toml"),
    )
    .unwrap();
    let (code, out) = cli(&[
        "new",
        &src.join("scaffold.toml").to_string_lossy(),
        "--out",
        &dir.to_string_lossy(),
    ]);
    assert_eq!(code, 0, "{out}");
    dir
}

#[test]
fn the_files_new_writes_for_a_data_package_are_exactly_the_gold_bytes() {
    let dir = made(
        "gold",
        &std::fs::read_to_string(example().join("scaffold.toml")).unwrap(),
    );
    for p in DATA {
        let gold = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("tests/data/gold/data")
            .join(format!("{p}.gold"));
        assert_eq!(
            std::fs::read(dir.join(p)).unwrap(),
            std::fs::read(&gold).unwrap_or_else(|e| panic!("no gold file for {p}: {e}")),
            "{p}"
        );
    }
}

#[test]
fn what_new_wrote_for_a_data_package_stays_green_under_the_drift_check() {
    let dir = made(
        "drift",
        &std::fs::read_to_string(example().join("scaffold.toml")).unwrap(),
    );
    let (code, out) = cli(&["check", "--repo", &dir.to_string_lossy(), "--drift"]);
    assert_eq!(code, 0, "{out}");
    assert!(
        !out.contains("generated-changed") && !out.contains("generated-missing"),
        "{out}"
    );
}

/// The `.desktop` of the RPM and the one of `packaging/` come from ONE template: equal but for the head line (and the program starts through the starter, never a binary of its own).
#[test]
fn the_desktop_of_the_rpm_is_the_desktop_of_packaging_without_the_head() {
    for (n, text) in [
        (
            "plain",
            std::fs::read_to_string(example().join("scaffold.toml")).unwrap(),
        ),
        (
            "icon",
            std::fs::read_to_string(example().join("scaffold.toml"))
                .unwrap()
                .replacen("[program]\n", "[program]\nicon = \"demo-icon\"\n", 1),
        ),
    ] {
        let bp = Blueprint::from_toml(&text).unwrap();
        let spec = program_spec(&bp, &example(), None, "1").unwrap();
        let rpm = spec
            .files
            .iter()
            .find(|f| f.dest.ends_with("net.freesynergy.Demo.desktop"))
            .and_then(|f| f.bytes.clone())
            .map(|b| String::from_utf8(b).unwrap())
            .unwrap();
        let dir = made(n, &text);
        let on_disk =
            std::fs::read_to_string(dir.join("packaging/net.freesynergy.Demo.desktop")).unwrap();
        let (head, body) = on_disk.split_once('\n').unwrap();
        assert!(head.starts_with("# generated by fs-blueprint"), "{head}");
        assert_eq!(body, rpm, "{n}");
        assert!(rpm.contains("Exec=fs-starter demo\n"), "{rpm}");
        assert_eq!(rpm.contains("Icon=demo-icon\n"), n == "icon", "{rpm}");
    }
}
