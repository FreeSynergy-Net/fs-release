//! Golden bytes: the exact output for the example blueprint of fs-tasks (one file per output file in `tests/data/gold/tasks/`, suffix `.gold`), with a fixed
//! blueprint hash. A change of the head line (process id, time), of a template (line endings, text) or of the canonical form of the blueprint (a new
//! version of the toml crate) turns this test red on purpose. After a change on purpose, the gold files are written again from the new output (and read by a person).
mod support;
use fs_blueprint::emit::header::blueprint_hash;
use fs_blueprint::Blueprint;
use std::path::Path;
use support::{generate, FakeCatalog, TASKS};

const HASH: &str = "167a6276086b90300ab857249fa1a2381991e2a6ab23b8115f9e4dcea298f0f4";

fn gold_dir() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/data/gold/tasks")
}

#[test]
fn the_output_for_the_tasks_example_is_exactly_the_gold_bytes() {
    let bp = Blueprint::from_toml(TASKS).unwrap();
    assert_eq!(blueprint_hash(&bp).unwrap(), HASH);
    let out = generate(&bp, &FakeCatalog).unwrap();
    assert_eq!(out.len(), 9);
    for a in &out {
        let want = std::fs::read(gold_dir().join(format!("{}.gold", a.path)))
            .unwrap_or_else(|e| panic!("no gold file for {}: {e}", a.path));
        assert_eq!(a.content.as_bytes(), want.as_slice(), "{}", a.path);
    }
}

#[test]
fn there_is_no_gold_file_without_an_output_file() {
    let bp = Blueprint::from_toml(TASKS).unwrap();
    let paths: Vec<String> = generate(&bp, &FakeCatalog)
        .unwrap()
        .into_iter()
        .map(|a| format!("{}.gold", a.path))
        .collect();
    let mut found = Vec::new();
    let mut todo = vec![gold_dir()];
    while let Some(d) = todo.pop() {
        for e in std::fs::read_dir(&d).unwrap() {
            let p = e.unwrap().path();
            if p.is_dir() {
                todo.push(p);
            } else {
                found.push(
                    p.strip_prefix(gold_dir())
                        .unwrap()
                        .to_string_lossy()
                        .replace('\\', "/"),
                );
            }
        }
    }
    found.sort();
    assert_eq!(found, paths);
}

#[test]
fn the_head_line_is_fixed_text_no_process_id_no_time() {
    let want = format!(
        "# generated by fs-blueprint {} from scaffold.toml sha256 {HASH}; content sha256 ",
        env!("CARGO_PKG_VERSION")
    );
    let bp = Blueprint::from_toml(TASKS).unwrap();
    let out = generate(&bp, &FakeCatalog).unwrap();
    let manifest = out.iter().find(|a| a.path == "Cargo.toml").unwrap();
    let head = manifest.content.lines().next().unwrap();
    assert!(head.starts_with(&want), "{head}");
    assert!(head.ends_with("; do not edit by hand"), "{head}");
    assert_eq!(head.len(), want.len() + 64 + "; do not edit by hand".len());
}
