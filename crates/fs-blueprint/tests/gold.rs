//! Golden bytes: the exact output for the example blueprint of fs-tasks, with a fixed blueprint hash. A change of the head line (process id, time),
//! of a template (line endings) or of the canonical form of the blueprint (a new version of the toml crate) turns this test red on purpose.
mod support;
use fs_blueprint::emit::generate;
use fs_blueprint::emit::header::blueprint_hash;
use fs_blueprint::{Blueprint, Class};
use support::{FakeCatalog, TASKS};

const HASH: &str = "da5356be763d0aea5847a78b5eb331393c3888e8ff63b81a217e8ae536c192f9";

const ATTRIBUTES: &str = "# generated by fs-blueprint 0.0.11 from scaffold.toml sha256 da5356be763d0aea5847a78b5eb331393c3888e8ff63b81a217e8ae536c192f9; do not edit by hand\n* text=auto eol=lf\n";

const MAIN: &str = r#"// generated by fs-blueprint 0.0.11 from scaffold.toml sha256 da5356be763d0aea5847a78b5eb331393c3888e8ff63b81a217e8ae536c192f9; do not edit by hand
//! Pattern: none (generated entry point: load the blueprint and start; exchangeable, nothing program-specific lives here).

/// The blueprint of this program, read at build time (reference: the file `scaffold.toml` in the repo root).
const BLUEPRINT: &str = include_str!("../../../scaffold.toml");
/// The program name (reference into the blueprint).
const PROGRAM: &str = "tasks";

fn main() {
    std::process::exit(start(PROGRAM, BLUEPRINT));
}

/// Placeholder of this generator step: the call of the shared starter replaces it (fs-starter pin, a later step); until then the entry only proves that the blueprint is there.
fn start(program: &str, blueprint: &str) -> i32 {
    eprintln!("{program}: blueprint with {} lines loaded", blueprint.lines().count());
    0
}
"#;

const SEED: &str = "// created by fs-blueprint 0.0.11; from now on this file belongs to the program and is never overwritten\n//! Pattern: none (the own core of fs-tasks: the domain code of the program lives here; the generator wrote this file once and never touches it again).\n";

#[test]
fn the_output_for_the_tasks_example_is_exactly_these_bytes() {
    let bp = Blueprint::from_toml(TASKS).unwrap();
    assert_eq!(blueprint_hash(&bp).unwrap(), HASH);
    let got: Vec<(String, Class, String)> = generate(&bp, &FakeCatalog)
        .unwrap()
        .into_iter()
        .map(|a| (a.path, a.class, a.content))
        .collect();
    let want = [
        (".gitattributes", Class::Generated, ATTRIBUTES),
        ("crates/fs-tasks-bin/src/main.rs", Class::Generated, MAIN),
        ("crates/fs-tasks-core/src/lib.rs", Class::Seed, SEED),
    ];
    assert_eq!(got.len(), want.len());
    for ((path, class, content), (wp, wc, wb)) in got.iter().zip(want) {
        assert_eq!((path.as_str(), *class), (wp, wc));
        assert_eq!(content.as_bytes(), wb.as_bytes(), "{path}");
    }
}

#[test]
fn the_head_line_is_the_same_in_a_new_process_no_process_id_no_time() {
    // the golden bytes above are fixed text, so a head line with a process id or a time differs between two test processes; here the head is also checked alone
    let bp = Blueprint::from_toml(TASKS).unwrap();
    let main = &generate(&bp, &FakeCatalog).unwrap()[1];
    assert_eq!(
        main.content.lines().next().unwrap(),
        MAIN.lines().next().unwrap()
    );
}
