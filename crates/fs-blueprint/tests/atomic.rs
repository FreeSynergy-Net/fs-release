//! `write` is atomic: a file is moved into place only when it is complete (a temporary file and a rename), and a failure while writing leaves nothing new behind.
mod support;
use fs_blueprint::emit::write::{write, DirStore, Found, Store};
use fs_blueprint::Artifact;
use fs_blueprint::Class;
use std::path::{Path, PathBuf};
use support::synth::blueprint;
use support::{generate, FakeCatalog};

fn dir(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("atomic-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

fn names(root: &Path) -> Vec<String> {
    let mut out = Vec::new();
    let mut todo = vec![root.to_path_buf()];
    while let Some(d) = todo.pop() {
        for e in std::fs::read_dir(&d).unwrap() {
            let p = e.unwrap().path();
            if p.is_dir() {
                todo.push(p);
            } else {
                out.push(
                    p.strip_prefix(root)
                        .unwrap()
                        .to_string_lossy()
                        .replace('\\', "/"),
                );
            }
        }
    }
    out.sort();
    out
}

#[test]
fn a_successful_write_leaves_no_temporary_file_and_replaces_an_older_generated_file() {
    let root = dir("ok");
    let mut store = DirStore::new(&root);
    let arts = generate(&blueprint(1), &FakeCatalog).unwrap();
    write(&arts, &mut store).unwrap();
    let files = names(&root);
    assert!(
        files.iter().all(|f| !f.contains("fs-blueprint-tmp")),
        "{files:?}"
    );
    let mut other = blueprint(1);
    other.program.summary.en = Some("something else".to_string());
    write(&generate(&other, &FakeCatalog).unwrap(), &mut store).unwrap();
    assert_eq!(names(&root), files, "the same files, replaced in place");
    assert!(std::fs::read_to_string(
        root.join("packaging")
            .join("net.freesynergy.BetaShelfPlanner.desktop")
    )
    .unwrap()
    .contains("something else"));
}

#[test]
fn a_failure_while_writing_leaves_nothing_new_behind() {
    let root = dir("fail");
    // a FILE where the folder `packaging` should be: the files before it in the list could be written, the ones under `packaging` cannot
    std::fs::write(root.join("packaging"), "i am a file").unwrap();
    let mut store = DirStore::new(&root);
    let arts = generate(&blueprint(1), &FakeCatalog).unwrap();
    let err = write(&arts, &mut store).unwrap_err();
    assert_eq!(err.len(), 1);
    assert_eq!(err[0].code, "write-failed");
    assert_eq!(
        names(&root),
        ["packaging"],
        "no new file and no temporary file"
    );
    assert_eq!(
        std::fs::read_to_string(root.join("packaging")).unwrap(),
        "i am a file"
    );
}

#[test]
fn a_failure_in_the_staging_step_keeps_the_old_content_of_every_file() {
    let root = dir("keep");
    let mut store = DirStore::new(&root);
    let a = Artifact::new("a.rs", Class::Generated, "// generated by fs-blueprint x\n");
    // the first write succeeds, the second one fails in the middle (the folder `b` is a file)
    store.put("a.rs", "old a\n").unwrap();
    std::fs::write(root.join("b"), "x").unwrap();
    let list = [("a.rs", "new a\n"), ("b/c.rs", "c\n")];
    assert_eq!(store.put_all(&list), Err("b/c.rs".to_string()));
    assert_eq!(store.read("a.rs"), Found::Text("old a\n".to_string()));
    assert_eq!(names(&root), ["a.rs", "b"]);
    let _ = a;
}

#[test]
fn a_stale_temporary_file_does_not_stop_the_next_write() {
    let root = dir("stale");
    std::fs::write(root.join(".a.rs.fs-blueprint-tmp"), "half").unwrap();
    let mut store = DirStore::new(&root);
    store.put("a.rs", "whole\n").unwrap();
    assert_eq!(
        std::fs::read_to_string(root.join("a.rs")).unwrap(),
        "whole\n"
    );
    assert_eq!(names(&root), ["a.rs"]);
}

fn failing_on_b(from: &Path, to: &Path) -> std::io::Result<()> {
    if to.file_name().is_some_and(|n| n == "b.rs") {
        return Err(std::io::Error::other("injected"));
    }
    std::fs::rename(from, to)
}

#[test]
fn a_failing_rename_leaves_no_temporary_file_and_names_the_file_that_failed() {
    let root = dir("rename");
    let mut store = DirStore::with_rename(&root, failing_on_b);
    let err = store
        .put_all(&[
            ("a.rs", "a\n"),
            ("b.rs", "b\n"),
            ("c.rs", "c\n"),
            ("d/e.rs", "e\n"),
        ])
        .unwrap_err();
    assert_eq!(err, "b.rs");
    // the files before the failed one are in place (the rename is the second step), the failed one and all after it are gone, and so are all temporary files
    assert_eq!(names(&root), ["a.rs"]);
    assert_eq!(std::fs::read_to_string(root.join("a.rs")).unwrap(), "a\n");
}

#[test]
fn a_failing_rename_is_a_write_failed_with_the_path_and_the_old_files_stay() {
    let root = dir("rename-write");
    let mut store = DirStore::with_rename(&root, failing_on_b);
    let arts = vec![
        Artifact::new("a.rs", Class::Generated, "// generated by fs-blueprint x\n"),
        Artifact::new("b.rs", Class::Generated, "// generated by fs-blueprint x\n"),
    ];
    let err = write(&arts, &mut store).unwrap_err();
    assert_eq!(
        err.iter().map(ToString::to_string).collect::<Vec<_>>(),
        ["write-failed{path=b.rs}"]
    );
    assert!(
        names(&root).iter().all(|n| !n.contains("fs-blueprint-tmp")),
        "{:?}",
        names(&root)
    );
}
