//! The repo on disk as the check sees it: files, folders, entry points, hand-written files under `crates/`, talk records; links are not followed.
use fs_blueprint::{FsRepo, RepoView};
use std::path::{Path, PathBuf};

fn tree(name: &str, files: &[(&str, &str)]) -> PathBuf {
    let root = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("repofs-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&root);
    for (p, c) in files {
        let f = p.split('/').fold(root.clone(), |a, s| a.join(s));
        std::fs::create_dir_all(f.parent().unwrap()).unwrap();
        std::fs::write(f, c).unwrap();
    }
    std::fs::create_dir_all(&root).unwrap();
    root
}

const GEN: &str = "// generated by fs-blueprint 0.0.17 from scaffold.toml sha256 x; content sha256 y; do not edit by hand\nfn a() {}\n";
const SEED: &str = "// created by fs-blueprint 0.0.17; from now on this file belongs to the program and is never overwritten\n";

#[test]
fn files_and_folders_exist_a_folder_only_with_the_end_slash_and_bad_paths_never() {
    let root = tree(
        "exists",
        &[("forms/a.toml", "x"), ("crates/x/src/lib.rs", "x")],
    );
    let r = FsRepo::new(&root, vec![], None);
    assert!(
        r.exists("forms/a.toml")
            && r.exists("forms/")
            && r.exists("forms")
            && r.exists("crates/x/src/lib.rs")
    );
    assert!(
        !r.exists("forms/b.toml")
            && !r.exists("forms/a.toml/")
            && !r.exists("../x")
            && !r.exists("")
            && !r.exists("a:b")
    );
}

#[test]
fn every_main_rs_is_found_also_nested_but_not_in_target_or_git() {
    let root = tree(
        "mains",
        &[
            ("crates/a/src/main.rs", "x"),
            ("main.rs", "x"),
            ("tools/b/main.rs", "x"),
            ("target/debug/main.rs", "x"),
            (".git/main.rs", "x"),
            ("crates/a/src/domain.rs", "x"),
        ],
    );
    assert_eq!(
        FsRepo::new(&root, vec![], None).main_files(),
        ["crates/a/src/main.rs", "main.rs", "tools/b/main.rs"]
    );
}

#[test]
fn files_under_crates_without_a_head_line_are_unowned_sorted_and_tests_are_left_out() {
    let root = tree(
        "unowned",
        &[
            ("crates/a/src/z.rs", "hand"),
            ("crates/a/src/a.rs", "hand"),
            ("crates/a/src/gen.rs", GEN),
            ("crates/a/src/seed.rs", SEED),
            ("crates/a/tests/t.rs", "hand"),
            ("crates/a/Cargo.toml", "# hand\n"),
            (
                "crates/b/src/head_in_second_line.rs",
                "x\n// generated by fs-blueprint 0.0.17 from scaffold.toml sha256 x\n",
            ),
            ("docs/x.md", "outside crates"),
            ("crates/a/target/x.rs", "built"),
        ],
    );
    let got = FsRepo::new(&root, vec![], None).unowned_files();
    assert_eq!(
        got,
        [
            "crates/a/Cargo.toml",
            "crates/a/src/a.rs",
            "crates/a/src/z.rs",
            "crates/b/src/head_in_second_line.rs"
        ]
    );
}

#[test]
fn a_file_that_is_not_text_is_unowned() {
    let root = tree("binary", &[]);
    std::fs::create_dir_all(root.join("crates").join("a")).unwrap();
    std::fs::write(
        root.join("crates").join("a").join("blob.bin"),
        [0xff, 0xfe, 0x00],
    )
    .unwrap();
    assert_eq!(
        FsRepo::new(&root, vec![], None).unowned_files(),
        ["crates/a/blob.bin"]
    );
}

#[test]
fn the_generated_paths_cover_a_file_or_a_folder_with_the_end_slash() {
    let r = FsRepo::new(
        "x",
        vec!["crates/a/src/main.rs".to_string(), "Cargo.toml".to_string()],
        None,
    );
    assert!(
        r.covers_generated("crates/a/src/main.rs")
            && r.covers_generated("crates/a/")
            && r.covers_generated("crates/")
            && r.covers_generated("Cargo.toml")
    );
    assert!(
        !r.covers_generated("crates/a")
            && !r.covers_generated("crates/b/")
            && !r.covers_generated("Cargo.tom")
    );
}

#[test]
fn talk_records_are_looked_for_in_the_documentation_checkout_only() {
    let docs = tree("docs", &[("conventions/talks/t.md", "x")]);
    let root = tree("talk", &[]);
    let with = FsRepo::new(&root, vec![], Some(docs));
    assert!(
        with.talk_exists("conventions/talks/t.md")
            && !with.talk_exists("conventions/talks/none.md")
            && !with.talk_exists("conventions/talks/")
            && !with.talk_exists("../x")
    );
    assert!(
        !FsRepo::new(&root, vec![], None).talk_exists("conventions/talks/t.md"),
        "without a checkout no record exists"
    );
}

#[test]
fn read_gives_the_text_and_nothing_for_a_missing_file_or_an_invalid_path() {
    let root = tree("read", &[("a.txt", "hello\n")]);
    let r = FsRepo::new(&root, vec![], None);
    assert_eq!(r.read("a.txt").as_deref(), Some("hello\n"));
    assert!(r.read("b.txt").is_none() && r.read("../a.txt").is_none() && r.read("").is_none());
}

#[cfg(unix)]
#[test]
fn a_link_is_never_followed_neither_as_a_file_nor_as_a_folder() {
    let outside = tree(
        "outside",
        &[("secret/main.rs", "x"), ("secret/lib.rs", "x")],
    );
    let root = tree("links", &[("crates/a/src/lib.rs", "hand")]);
    std::os::unix::fs::symlink(outside.join("secret"), root.join("crates").join("linked")).unwrap();
    std::os::unix::fs::symlink(outside.join("secret"), root.join("tools")).unwrap();
    let r = FsRepo::new(&root, vec![], None);
    assert_eq!(r.unowned_files(), ["crates/a/src/lib.rs"]);
    assert_eq!(r.main_files(), Vec::<String>::new());
}

#[test]
fn a_talk_path_that_leaves_the_checkout_is_never_a_record_even_when_the_file_is_there() {
    let docs = tree("talk-escape", &[("conventions/talks/t.md", "x")]);
    let beside = docs.parent().unwrap().join("beside-the-checkout.md");
    std::fs::write(&beside, "x").unwrap();
    let r = FsRepo::new("x", vec![], Some(docs));
    assert!(r.talk_exists("conventions/talks/t.md"));
    assert!(
        !r.talk_exists("../beside-the-checkout.md")
            && !r.talk_exists("conventions/../../beside-the-checkout.md")
    );
}
