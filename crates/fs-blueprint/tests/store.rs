//! E3-3: the tables of the program's own types: gold, typed columns, child tables for lists, no JSON column.
mod support;
use fs_blueprint::emit::header::{class_of, form_of, Form};
use fs_blueprint::emit::Class;
use fs_blueprint::Blueprint;
use support::{edit, generate, FakeCatalog, SHIFT, TASKS};

const GOLD: &str = "-- Tables of schedules for contract 0.1: typed columns, no JSON column.

CREATE TABLE shift (
  id INTEGER PRIMARY KEY,
  span TEXT
);

CREATE TABLE shift_assignee (
  owner INTEGER NOT NULL REFERENCES shift(id),
  pos INTEGER NOT NULL,
  value TEXT NOT NULL,
  PRIMARY KEY (owner, pos)
);
";

fn tables_of(src: &str) -> Option<String> {
    let bp = Blueprint::from_toml(src).unwrap();
    let all = generate(&bp, &FakeCatalog).unwrap();
    let a = all.iter().find(|a| a.path == "schema/schedules.sql")?;
    assert_eq!(a.class, Class::Generated);
    assert_eq!(class_of(&a.content), Some(Class::Generated));
    Some(a.content.split_once('\n').unwrap().1.to_string())
}

fn with_field(basic: &str) -> String {
    edit(
        SHIFT,
        "\n[frontend]",
        &format!("\n[[type.field]]\nname = \"dueDate\"\nbasic = \"{basic}\"\nstandard = \"https://x.org/a#b\"\nlabel = {{ en = \"a\", de = \"b\" }}\n\n[frontend]"),
    )
}

#[test]
fn the_table_text_is_the_gold() {
    assert_eq!(tables_of(SHIFT).as_deref(), Some(GOLD));
}

#[test]
fn basic_types_become_typed_columns_in_snake_case() {
    for (basic, line) in [
        ("integer", "  due_date INTEGER\n"),
        ("flag", "  due_date BOOLEAN\n"),
        ("text", "  due_date TEXT\n"),
    ] {
        assert!(
            tables_of(&with_field(basic)).unwrap().contains(line),
            "{basic}"
        );
    }
    // a keywords field is a list: its own table, not a column
    let text = tables_of(&with_field("keywords")).unwrap();
    assert!(text.contains("CREATE TABLE shift_due_date ("));
    assert!(!text.contains("  due_date "));
}

#[test]
fn no_table_holds_a_json_column() {
    // the comment lines say "no JSON column"; only the statements count
    let text: String = tables_of(SHIFT)
        .unwrap()
        .lines()
        .filter(|l| !l.starts_with("--"))
        .collect::<Vec<_>>()
        .join("\n")
        .to_lowercase();
    assert!(!text.contains("json") && !text.contains("blob"));
}

#[test]
fn the_sql_head_line_is_a_dash_comment() {
    assert_eq!(form_of("schema/x.sql"), Some(Form::Dash));
    assert!(tables_of(SHIFT).is_some());
    let bp = Blueprint::from_toml(SHIFT).unwrap();
    let all = generate(&bp, &FakeCatalog).unwrap();
    let a = all
        .iter()
        .find(|a| a.path == "schema/schedules.sql")
        .unwrap();
    assert!(a.content.starts_with("-- generated by fs-blueprint "));
}

#[test]
fn a_program_without_own_types_has_no_tables() {
    assert_eq!(tables_of(TASKS), None);
}
