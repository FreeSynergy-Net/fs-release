//! `write` and the generator against data loss and escape: unreadable files, links, paths out of the repo,
mod support;
use fs_blueprint::emit::write::{write, DirStore, Found, Store};
use fs_blueprint::{Artifact, Class, Coded};
use std::path::{Path, PathBuf};
#[cfg(windows)]
use std::process::{Command, Stdio};
use support::synth::{blueprint, MemStore};
use support::{generate, FakeCatalog};

const MAIN: &str = "crates/fs-beta-shelf-planner-bin/Cargo.toml";
const BIN_FILES: [&str; 1] = ["Cargo.toml"];
const SEED: &str = "crates/fs-beta-shelf-planner-core/Cargo.toml";

fn dir(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("safety-{name}-{}", std::process::id()));
    std::fs::create_dir_all(&d).unwrap();
    d
}

fn put_bytes(root: &Path, path: &str, bytes: &[u8]) {
    let f = path.split('/').fold(root.to_path_buf(), |p, c| p.join(c));
    std::fs::create_dir_all(f.parent().unwrap()).unwrap();
    std::fs::write(f, bytes).unwrap();
}

fn codes(r: Result<fs_blueprint::emit::write::Outcome, Vec<Coded>>) -> Vec<String> {
    r.unwrap_err().iter().map(ToString::to_string).collect()
}

fn arts() -> Vec<Artifact> {
    generate(&blueprint(1), &FakeCatalog).unwrap()
}

#[test]
fn a_seed_that_is_not_utf8_is_kept_and_never_overwritten() {
    let root = dir("seed");
    let bad: &[u8] = &[0xff, 0xfe, 0x00, 0x41];
    put_bytes(&root, SEED, bad);
    let mut store = DirStore::new(&root);
    assert_eq!(store.read(SEED), Found::Unreadable);
    let out = write(&arts(), &mut store).unwrap();
    assert_eq!(out.kept, [SEED]);
    assert_eq!(
        std::fs::read(SEED.split('/').fold(root.clone(), |p, c| p.join(c))).unwrap(),
        bad
    );
}

#[test]
fn a_hand_written_non_utf8_file_at_a_generated_path_is_refused_and_nothing_is_written() {
    let root = dir("gen");
    let bad: &[u8] = &[0xc3, 0x28, 0xff];
    put_bytes(&root, MAIN, bad);
    let mut store = DirStore::new(&root);
    assert_eq!(
        codes(write(&arts(), &mut store)),
        [format!("file-unreadable{{path={MAIN}}}")]
    );
    assert_eq!(
        std::fs::read(MAIN.split('/').fold(root.clone(), |p, c| p.join(c))).unwrap(),
        bad
    );
    assert!(
        !root.join(".gitattributes").exists(),
        "nothing else was written"
    );
}

#[test]
fn a_folder_at_the_path_of_a_generated_file_is_refused() {
    let root = dir("folder");
    std::fs::create_dir_all(MAIN.split('/').fold(root.clone(), |p, c| p.join(c))).unwrap();
    let mut store = DirStore::new(&root);
    assert_eq!(
        codes(write(&arts(), &mut store)),
        [format!("file-unreadable{{path={MAIN}}}")]
    );
}

#[test]
fn paths_that_leave_the_repo_are_refused_before_anything_is_written() {
    for bad in [
        "../escaped.rs",
        "/abs/x.rs",
        "C:/x.rs",
        "a\\b.rs",
        "a/../../b.rs",
        "a/./b.rs",
        "",
    ] {
        let root = dir("escape");
        let mut store = DirStore::new(root.join("repo"));
        let list = vec![
            Artifact::new(
                "ok.rs",
                Class::Generated,
                "// generated by fs-blueprint x\n",
            ),
            Artifact::new(bad, Class::Generated, "x\n"),
        ];
        assert_eq!(
            codes(write(&list, &mut store)),
            [format!("path-invalid{{path={bad}}}")],
            "{bad:?}"
        );
        assert!(!root.join("repo").exists(), "{bad:?}: nothing written");
        assert!(!root.join("escaped.rs").exists());
    }
}

#[cfg(unix)]
#[test]
fn a_link_in_the_path_is_refused_for_a_folder_and_for_the_file() {
    let root = dir("link");
    let outside = dir("outside");
    std::fs::create_dir_all(root.join("crates")).unwrap();
    std::os::unix::fs::symlink(
        &outside,
        root.join("crates").join("fs-beta-shelf-planner-bin"),
    )
    .unwrap();
    let mut store = DirStore::new(&root);
    let got = codes(write(&arts(), &mut store));
    assert_eq!(
        got,
        BIN_FILES.map(|f| format!("path-symlink{{path=crates/fs-beta-shelf-planner-bin/{f}}}"))
    );
    assert!(
        std::fs::read_dir(&outside).unwrap().next().is_none(),
        "nothing written through the link"
    );
    let root2 = dir("link2");
    put_bytes(&root2, "target.txt", b"x");
    std::fs::create_dir_all(root2.join(".gitattributes.d")).unwrap();
    std::os::unix::fs::symlink(root2.join("target.txt"), root2.join(".gitattributes")).unwrap();
    assert_eq!(
        codes(write(&arts(), &mut DirStore::new(&root2))),
        ["path-symlink{path=.gitattributes}".to_string()]
    );
    assert_eq!(std::fs::read(root2.join("target.txt")).unwrap(), b"x");
}

/// A link to a folder: a symbolic link on Unix, a junction on Windows (made with `mklink /J`, which needs no rights).
fn link_dir(link: &Path, target: &Path) {
    #[cfg(unix)]
    std::os::unix::fs::symlink(target, link).unwrap();
    #[cfg(windows)]
    {
        let ok = Command::new("cmd")
            .args(["/C", "mklink", "/J"])
            .arg(link)
            .arg(target)
            .stdout(Stdio::null())
            .status()
            .unwrap()
            .success();
        assert!(ok, "mklink /J failed");
    }
}

#[test]
fn put_itself_refuses_a_link_even_when_called_directly() {
    let root = dir("putlink");
    let outside = dir("putoutside");
    link_dir(&root.join("l"), &outside);
    let mut store = DirStore::new(&root);
    assert!(!store.path_ok("l/x.rs"));
    assert!(store.put("l/x.rs", "x").is_err());
    assert!(!outside.join("x.rs").exists());
    assert!(MemStore::default().path_ok("a/b"));
}

#[test]
fn a_link_to_a_folder_on_the_way_is_refused_by_write_on_every_platform() {
    let root = dir("linkdir");
    let outside = dir("linkdir-out");
    std::fs::create_dir_all(root.join("crates")).unwrap();
    link_dir(
        &root.join("crates").join("fs-beta-shelf-planner-bin"),
        &outside,
    );
    let got = codes(write(&arts(), &mut DirStore::new(&root)));
    assert_eq!(
        got,
        BIN_FILES.map(|f| format!("path-symlink{{path=crates/fs-beta-shelf-planner-bin/{f}}}"))
    );
    assert!(std::fs::read_dir(&outside).unwrap().next().is_none());
}
