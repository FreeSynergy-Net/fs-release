//! Pattern: Decorator (the head line of a generated or seeded file in the comment form of its kind; no time stamp, no path of the machine).

use super::artifact::Class;
use crate::error::Coded;
use crate::model::Blueprint;
use sha2::{Digest, Sha256};
use std::fmt::Write;

/// The tool name as it stands in every head.
pub const TOOL: &str = "fs-blueprint";
const GENERATED: &str = "generated by fs-blueprint ";
const SEEDED: &str = "created by fs-blueprint ";

/// The three comment forms of a head line.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Form {
    /// `// text` (Rust)
    Slash,
    /// `# text` (TOML, YAML, desktop files, gitattributes)
    Hash,
    /// `<!-- text -->` (Markdown, XML, HTML)
    Html,
}

/// The comment form for a repo path, by its file name; `None` for a kind that has no comment (no head possible).
#[must_use]
pub fn form_of(path: &str) -> Option<Form> {
    let name = path.rsplit('/').next().unwrap_or(path);
    let ends = |list: &[&str]| list.iter().any(|e| name.ends_with(e));
    if ends(&[".rs"]) {
        Some(Form::Slash)
    } else if name == ".gitattributes" || ends(&[".toml", ".yml", ".yaml", ".desktop"]) {
        Some(Form::Hash)
    } else if ends(&[".md", ".xml", ".html"]) {
        Some(Form::Html)
    } else {
        None
    }
}

fn wrap(form: Form, text: &str) -> String {
    match form {
        Form::Slash => format!("// {text}\n"),
        Form::Hash => format!("# {text}\n"),
        Form::Html => format!("<!-- {text} -->\n"),
    }
}

/// SHA-256 of the blueprint in its canonical form (the TOML text of the parsed value: fixed field order, no comments, no white space of the author).
///
/// # Errors
/// `blueprint-unserializable` when the value cannot be written as TOML (does not happen for a parsed blueprint).
pub fn blueprint_hash(bp: &Blueprint) -> Result<String, Coded> {
    let text = toml::to_string(bp).map_err(|_| Coded::new("blueprint-unserializable"))?;
    let mut hex = String::with_capacity(64);
    for b in Sha256::digest(text.as_bytes()) {
        write!(hex, "{b:02x}").map_err(|_| Coded::new("blueprint-unserializable"))?;
    }
    Ok(hex)
}

/// The head line of a class (`Exception` has none): generated files carry the tool version and the blueprint hash, seeds only the tool version.
#[must_use]
pub fn head_line(class: Class, form: Form, hash: &str) -> Option<String> {
    let version = env!("CARGO_PKG_VERSION");
    match class {
        Class::Generated => Some(wrap(
            form,
            &format!("{GENERATED}{version} from scaffold.toml sha256 {hash}; do not edit by hand"),
        )),
        Class::Seed => Some(wrap(
            form,
            &format!("{SEEDED}{version}; from now on this file belongs to the program and is never overwritten"),
        )),
        Class::Exception => None,
    }
}

/// The body with its head line on top.
///
/// # Errors
/// `header-unsupported{path}` when the file kind has no comment form.
pub fn stamp(path: &str, class: Class, hash: &str, body: &str) -> Result<String, Coded> {
    let Some(form) = form_of(path) else {
        return Err(Coded::new("header-unsupported").with("path", path));
    };
    Ok(head_line(class, form, hash).map_or_else(|| body.to_string(), |h| format!("{h}{body}")))
}

/// The text of a head line without its comment marks, or `None` when the line is no comment.
fn uncomment(line: &str) -> Option<&str> {
    let line = line.trim_end();
    if let Some(t) = line.strip_prefix("// ").or_else(|| line.strip_prefix("# ")) {
        return Some(t);
    }
    line.strip_prefix("<!-- ")?.strip_suffix(" -->")
}

/// The first line of a file when it is a head line of this tool: the class it names (`Generated` or `Seed`).
#[must_use]
pub fn class_of(content: &str) -> Option<Class> {
    let text = uncomment(content.lines().next()?)?;
    if text.starts_with(GENERATED) {
        Some(Class::Generated)
    } else if text.starts_with(SEEDED) {
        Some(Class::Seed)
    } else {
        None
    }
}

/// The first line of a file (the head line when there is one).
#[must_use]
pub fn first_line(content: &str) -> &str {
    content.lines().next().unwrap_or("")
}
